// Builds brand/preview.html from tokens.json and mascot-layered.svg.
// Logos are linked with <img> so they always show the current file; the mascot is copied inline
// so that CSS can animate its #head and #rice groups. Rerun after the mascot or tokens change.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { parseSync, stringify } from 'svgson';
import { isDirectRun } from './lib/run.mjs';
import { contrast, findById } from './lib/svg-check.mjs';

const brandDir = fileURLToPath(new URL('../', import.meta.url));
const previewPath = `${brandDir}preview.html`;

const LOGOS = ['logo-full', 'logo-icon', 'logo-mono'];
// On the dark background, the light versions of logo-full and logo-mono.
const LIGHT_LOGOS = ['logo-full-light', 'logo-icon', 'logo-mono-light'];
const BACKGROUNDS = [
  { token: 'trang-gao', name: 'Trắng gạo', text: 'nau-dat', logos: LOGOS },
  { token: 'vang-rom', name: 'Vàng rơm', text: 'nau-dat', logos: LOGOS },
  { token: 'nau-dat', name: 'Nâu đất', text: 'trang-gao', logos: LIGHT_LOGOS },
];
const ICON_SIZES = [16, 32, 64, 192];
const SWAY_DEGREES = { head: 3, rice: 6 };
const WCAG_AA = 4.5;
const SAMPLE_TEXT = 'Gạo nếp cái hoa vàng Xứ Đông';

const escapeHtml = (text) =>
  text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

// The mascot SVG with the transform origin of each animated group taken from its data-pivot.
function inlineMascot(svgString) {
  const root = parseSync(svgString);
  delete root.attributes.width;
  delete root.attributes.height;
  root.attributes.class = 'mascot';
  root.attributes.role = 'img';
  root.attributes['aria-label'] = 'Mascot Nếp Nhà';
  for (const id of Object.keys(SWAY_DEGREES)) {
    const group = findById(root, id);
    const pivot = group?.attributes['data-pivot'];
    if (pivot === undefined) throw new Error(`mascot: no <g id="${id}"> with data-pivot`);
    const [x, y] = pivot.trim().split(/\s+/);
    group.attributes.style = `transform-box: view-box; transform-origin: ${x}px ${y}px`;
  }
  return stringify(root);
}

const formatRatio = (ratio) => `${ratio.toFixed(2).replace('.', ',')} : 1`;

export function buildPreview() {
  const tokens = JSON.parse(readFileSync(`${brandDir}tokens/tokens.json`, 'utf8'));
  const mascot = inlineMascot(readFileSync(`${brandDir}mascot/mascot-layered.svg`, 'utf8'));
  const hex = (token) => tokens.color[token].value;

  const logoPanels = BACKGROUNDS.map(
    ({ token, name, text, logos }) => `
      <div class="panel" style="background: var(--color-${token}); color: var(--color-${text})">
        <h3>Nền ${name} <code>${hex(token)}</code></h3>
        <div class="logos">
${logos.map((logo) => `          <figure><img src="logo/${logo}.svg" alt="${logo}"><figcaption>${logo}</figcaption></figure>`).join('\n')}
        </div>
      </div>`,
  ).join('');

  const icons = ICON_SIZES.map(
    (size) =>
      `        <figure><img src="logo/logo-icon.svg" width="${size}" height="${size}" alt="logo-icon ${size} px"><figcaption>${size} px</figcaption></figure>`,
  ).join('\n');

  const swatches = Object.entries(tokens.color)
    .map(
      ([token, { value, use }]) => `
        <div class="swatch">
          <div class="chip" style="background: var(--color-${token})"></div>
          <strong>${token}</strong> <code>${value}</code>
          <p>${escapeHtml(use)}</p>
        </div>`,
    )
    .join('');

  const pairs = tokens.textPairs
    .map(([text, background]) => {
      const ratio = contrast(hex(text), hex(background));
      const verdict = ratio >= WCAG_AA ? 'Đạt AA' : 'Không đạt AA';
      return `
        <div class="pair" style="color: var(--color-${text}); background: var(--color-${background})">
          <p class="sample">${SAMPLE_TEXT}</p>
          <p>Chữ ${text} trên nền ${background}: <strong>${formatRatio(ratio)}</strong> (${verdict})</p>
        </div>`;
    })
    .join('');

  const keyframes = Object.entries(SWAY_DEGREES)
    .map(
      ([id, degrees]) => `
    @keyframes ${id}-sway {
      from { transform: rotate(-${degrees}deg); }
      to { transform: rotate(${degrees}deg); }
    }
    .mascot #${id} { animation: ${id}-sway ${id === 'head' ? 2.4 : 1.8}s ease-in-out infinite alternate; }`,
    )
    .join('');

  return `<!doctype html>
<!-- Generated by brand/tools/build-preview.mjs. Do not edit by hand: run "npm run preview" in brand/tools. -->
<html lang="vi">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>Nếp Nhà - bộ nhận diện</title>
  <link rel="stylesheet" href="tokens/tokens.css">
  <style>
    @font-face { font-family: 'Pacifico'; src: url('fonts/Pacifico-Regular.ttf'); }
    @font-face { font-family: 'Quicksand'; font-weight: 400; src: url('fonts/Quicksand-400.ttf'); }
    @font-face { font-family: 'Quicksand'; font-weight: 500; src: url('fonts/Quicksand-500.ttf'); }
    @font-face { font-family: 'Quicksand'; font-weight: 700; src: url('fonts/Quicksand-700.ttf'); }
    body { margin: 0; padding: 24px 16px 48px; background: var(--color-trang-gao); color: var(--color-nau-dat); font-family: var(--font-body); }
    main { max-width: 1100px; margin: 0 auto; }
    h1 { font-family: var(--font-display); font-weight: 400; font-size: 48px; margin: 0 0 8px; }
    h2 { font-weight: 700; margin: 40px 0 16px; }
    h3 { font-weight: 500; font-size: 16px; margin: 0 0 16px; }
    code { font-size: 13px; }
    figure { margin: 0; text-align: center; }
    figcaption { font-size: 13px; margin-top: 6px; }
    .panel { border-radius: 12px; padding: 20px; margin-bottom: 16px; }
    .logos { display: flex; flex-wrap: wrap; gap: 32px; align-items: flex-end; }
    .logos img { height: 200px; max-width: 100%; }
    .icons { display: flex; flex-wrap: wrap; gap: 32px; align-items: flex-end; }
    .mascot { width: min(360px, 100%); height: auto; display: block; }${keyframes}
    @media (prefers-reduced-motion: reduce) {
      .mascot #head, .mascot #rice { animation: none; }
    }
    .swatches { display: grid; grid-template-columns: repeat(auto-fill, minmax(200px, 1fr)); gap: 16px; }
    .chip { height: 64px; border-radius: 8px; border: 1px solid var(--color-nau-dat); margin-bottom: 8px; }
    .swatch p { font-size: 13px; margin: 4px 0 0; }
    .pairs { display: grid; grid-template-columns: repeat(auto-fill, minmax(300px, 1fr)); gap: 16px; }
    .pair { border-radius: 8px; padding: 16px; border: 1px solid var(--color-nau-dat); }
    .pair p { margin: 0; font-size: 14px; }
    .pair .sample { font-size: 18px; font-weight: 500; margin-bottom: 8px; }
  </style>
</head>
<body>
<main>
  <h1>Nếp Nhà</h1>
  <p>Trang xem bộ nhận diện: logo, biểu tượng, mascot, bảng màu.</p>

  <h2>Logo trên 3 nền</h2>${logoPanels}

  <h2>Biểu tượng ở các cỡ</h2>
  <div class="panel" style="background: var(--color-trang-gao); border: 1px solid var(--color-vang-rom)">
    <div class="icons">
${icons}
    </div>
  </div>

  <h2>Mascot (đầu xoay ±${SWAY_DEGREES.head}°, bó lúa xoay ±${SWAY_DEGREES.rice}°)</h2>
  <div class="panel" style="background: var(--color-vang-rom)">
    ${mascot}
  </div>

  <h2>Bảng màu</h2>
  <div class="swatches">${swatches}
  </div>

  <h2>Cặp chữ / nền và tỷ lệ tương phản</h2>
  <div class="pairs">${pairs}
  </div>
</main>
</body>
</html>
`;
}

if (isDirectRun(import.meta.url)) {
  writeFileSync(previewPath, buildPreview());
  console.log(`preview.html written`);
}
