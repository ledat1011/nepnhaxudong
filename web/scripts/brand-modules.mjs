import { assertSafe } from "./svg-safety.mjs";

const REQUIRED_GROUPS = ["head", "rice", "hands", "body"];
const PIVOT_GROUPS = ["head", "rice"];

function splitSvg(svg, name) {
  const open = svg.match(/<svg\b[^>]*>/);
  const close = svg.lastIndexOf("</svg>");
  if (open === null || close === -1) throw new Error(`${name} is not an svg document`);
  const viewBox = open[0].match(/\sviewBox="([^"]+)"/);
  if (viewBox === null) throw new Error(`${name} has no viewBox`);
  // Whitespace between tags is dropped so the SVG adds no text nodes to the page.
  const inner = svg.slice(open.index + open[0].length, close).replace(/>\s+</g, "><").trim();
  return { viewBox: viewBox[1], inner };
}

function groupTag(inner, id) {
  const tag = inner.match(new RegExp(`<g\\b[^>]*\\sid="${id}"[^>]*>`));
  if (tag === null) throw new Error(`mascot has no #${id} group`);
  return tag[0];
}

function readPivot(tag, id) {
  const pivot = tag.match(/\sdata-pivot="\s*(-?[\d.]+)[\s,]+(-?[\d.]+)\s*"/);
  if (pivot === null) throw new Error(`mascot #${id} has no data-pivot`);
  return { x: Number(pivot[1]), y: Number(pivot[2]) };
}

function moduleSource(file, lines) {
  return [`// Generated by "npm run brand:sync" from brand/${file}. Do not edit.`, ...lines, ""].join("\n");
}

/** Builds the source of the two generated TypeScript modules from the brand SVG files. */
export function buildBrandModules({ mascotSvg, logoIconSvg }) {
  assertSafe(mascotSvg, "mascot-layered.svg");
  assertSafe(logoIconSvg, "logo-icon.svg");

  const mascot = splitSvg(mascotSvg, "mascot-layered.svg");
  for (const id of REQUIRED_GROUPS) groupTag(mascot.inner, id);
  const pivots = {};
  for (const id of PIVOT_GROUPS) pivots[id] = readPivot(groupTag(mascot.inner, id), id);

  const logo = splitSvg(logoIconSvg, "logo-icon.svg");

  const mascotTs = moduleSource("mascot/mascot-layered.svg", [
    `export const MASCOT_VIEWBOX: string = ${JSON.stringify(mascot.viewBox)};`,
    `export const MASCOT_INNER: string = ${JSON.stringify(mascot.inner)};`,
    `export const MASCOT_PIVOTS: { head: { x: number; y: number }; rice: { x: number; y: number } } = ${JSON.stringify(pivots)};`,
  ]);
  const logoIconTs = moduleSource("logo/logo-icon.svg", [
    `export const LOGO_ICON_VIEWBOX: string = ${JSON.stringify(logo.viewBox)};`,
    `export const LOGO_ICON_INNER: string = ${JSON.stringify(logo.inner)};`,
  ]);
  return { mascotTs, logoIconTs };
}
