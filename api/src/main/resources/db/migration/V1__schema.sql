-- Schema for the Nếp Nhà website API.
-- Conventions: snake_case names, bigint identity primary keys (by default, so that a deleted row
-- can be restored with its old id), timestamptz for all times, languages are 'vi' and 'en'.

create table app_user (
    id                   bigint generated by default as identity primary key,
    email                text        not null,
    display_name         text        not null,
    password_hash        text        not null,
    must_change_password boolean     not null default true,
    enabled              boolean     not null default true,
    failed_attempts      int         not null default 0,
    locked_until         timestamptz,
    totp_secret          text,
    totp_enabled         boolean     not null default false,
    created_at           timestamptz not null default now(),
    updated_at           timestamptz not null default now(),
    constraint app_user_email_lower check (email = lower(email)),
    constraint app_user_email_unique unique (email)
);

create table media (
    id         bigint generated by default as identity primary key,
    path       text        not null,
    mime       text        not null,
    width      int         not null,
    height     int         not null,
    size_bytes bigint      not null,
    alt_vi     text        not null,
    alt_en     text        not null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint media_path_unique unique (path)
);

create table product (
    id         bigint generated by default as identity primary key,
    sort_order int         not null default 0,
    show_price boolean     not null default false,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table product_translation (
    id           bigint generated by default as identity primary key,
    product_id   bigint not null references product (id) on delete cascade,
    lang         text   not null,
    name         text   not null,
    description  text,
    features     jsonb  not null default '[]'::jsonb,
    cooking_tips text,
    constraint product_translation_lang check (lang in ('vi', 'en')),
    constraint product_translation_features_array check (jsonb_typeof(features) = 'array'),
    constraint product_translation_unique unique (product_id, lang)
);

create table packaging (
    id           bigint generated by default as identity primary key,
    product_id   bigint      not null references product (id) on delete cascade,
    weight_grams int         not null,
    price_vnd    bigint,
    sort_order   int         not null default 0,
    created_at   timestamptz not null default now(),
    updated_at   timestamptz not null default now(),
    constraint packaging_weight_positive check (weight_grams > 0),
    constraint packaging_price_not_negative check (price_vnd is null or price_vnd >= 0)
);
create index packaging_product_idx on packaging (product_id);

create table product_media (
    id         bigint generated by default as identity primary key,
    product_id bigint      not null references product (id) on delete cascade,
    media_id   bigint      not null references media (id) on delete restrict,
    sort_order int         not null default 0,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint product_media_unique unique (product_id, media_id)
);
create index product_media_media_idx on product_media (media_id);

create table timeline_event (
    id         bigint generated by default as identity primary key,
    year       int         not null,
    sort_order int         not null default 0,
    media_id   bigint references media (id) on delete restrict,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);
create index timeline_event_media_idx on timeline_event (media_id);

create table timeline_event_translation (
    id                bigint generated by default as identity primary key,
    timeline_event_id bigint not null references timeline_event (id) on delete cascade,
    lang              text   not null,
    title             text   not null,
    description       text,
    constraint timeline_event_translation_lang check (lang in ('vi', 'en')),
    constraint timeline_event_translation_unique unique (timeline_event_id, lang)
);

create table press_mention (
    id           bigint generated by default as identity primary key,
    url          text        not null,
    source_name  text        not null,
    published_on date,
    media_id     bigint references media (id) on delete restrict,
    sort_order   int         not null default 0,
    created_at   timestamptz not null default now(),
    updated_at   timestamptz not null default now()
);
create index press_mention_media_idx on press_mention (media_id);

create table press_mention_translation (
    id               bigint generated by default as identity primary key,
    press_mention_id bigint not null references press_mention (id) on delete cascade,
    lang             text   not null,
    title            text   not null,
    constraint press_mention_translation_lang check (lang in ('vi', 'en')),
    constraint press_mention_translation_unique unique (press_mention_id, lang)
);

create table story (
    id             bigint generated by default as identity primary key,
    status         text        not null default 'DRAFT',
    published_at   timestamptz,
    cover_media_id bigint references media (id) on delete restrict,
    created_at     timestamptz not null default now(),
    updated_at     timestamptz not null default now(),
    constraint story_status check (status in ('DRAFT', 'PUBLISHED')),
    constraint story_published_has_date check (status <> 'PUBLISHED' or published_at is not null)
);
create index story_cover_media_idx on story (cover_media_id);
create index story_list_idx on story (status, published_at desc, id desc);

create table story_translation (
    id         bigint generated by default as identity primary key,
    story_id   bigint not null references story (id) on delete cascade,
    lang       text   not null,
    slug       text   not null,
    title      text   not null,
    excerpt    text,
    body_html  text   not null default '',
    constraint story_translation_lang check (lang in ('vi', 'en')),
    constraint story_translation_story_lang_unique unique (story_id, lang),
    constraint story_translation_lang_slug_unique unique (lang, slug)
);

create table site_setting (
    id         bigint generated by default as identity primary key,
    key        text        not null,
    value      jsonb       not null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint site_setting_key_unique unique (key)
);

create table audit_log (
    id          bigint generated by default as identity primary key,
    user_id     bigint references app_user (id) on delete set null,
    entity_type text        not null,
    entity_id   bigint      not null,
    action      text        not null,
    before_json jsonb,
    after_json  jsonb,
    created_at  timestamptz not null default now(),
    constraint audit_log_action check (action in ('CREATE', 'UPDATE', 'DELETE', 'RESTORE'))
);
create index audit_log_entity_idx on audit_log (entity_type, entity_id);
create index audit_log_user_idx on audit_log (user_id);
create index audit_log_created_idx on audit_log (created_at desc, id desc);
