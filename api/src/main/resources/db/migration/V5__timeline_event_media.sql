-- A milestone holds 0 to 3 ordered images (spec 2026-11-06-hanh-trinh-nhieu-anh), like product_media.
-- The single image of an existing milestone becomes the first row of its list.
create table timeline_event_media (
    id                bigint generated by default as identity primary key,
    timeline_event_id bigint      not null references timeline_event (id) on delete cascade,
    media_id          bigint      not null references media (id) on delete restrict,
    sort_order        int         not null default 0,
    created_at        timestamptz not null default now(),
    updated_at        timestamptz not null default now(),
    constraint timeline_event_media_unique unique (timeline_event_id, media_id)
);

insert into timeline_event_media (timeline_event_id, media_id, sort_order)
select id, media_id, 0
from timeline_event
where media_id is not null;

-- The old index has the name "timeline_event_media_idx"; it goes first, and the new index of the
-- list table gets a different name, so the two can never be mixed up.
drop index timeline_event_media_idx;
alter table timeline_event drop column media_id;
create index timeline_event_media_media_idx on timeline_event_media (media_id);
