package vn.nepnhaxudong.product;

import java.sql.Timestamp;
import java.time.Clock;
import java.util.HashSet;
import java.util.List;
import java.util.Optional;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;
import tools.jackson.core.JacksonException;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.json.JsonMapper;
import vn.nepnhaxudong.audit.JsonAuditedHandler;
import vn.nepnhaxudong.common.ApiException;
import vn.nepnhaxudong.media.MediaReferences;

/**
 * Reads and restores products for the audit log. A deleted product is inserted again with its old
 * id (the id column is "generated by default", so an explicit id is accepted); its translations,
 * pack sizes and image links are then created through the normal entity code.
 *
 * <p>"Hiện trên web" is never changed as a side effect of restoring other fields: an existing
 * product keeps its current value, and a deleted product comes back hidden. Only a line that itself
 * changed the switch (a show or a hide) puts the value of its "before" back.
 */
@Component
class ProductAuditedHandler extends JsonAuditedHandler<ProductAdminDto> {

  private final ProductRepository products;
  private final ProductService service;
  private final MediaReferences mediaReferences;
  private final JdbcTemplate jdbc;
  private final Clock clock;
  private final JsonMapper json;

  ProductAuditedHandler(
      ProductRepository products,
      ProductService service,
      MediaReferences mediaReferences,
      JdbcTemplate jdbc,
      Clock clock,
      JsonMapper json) {
    super(ProductService.AUDIT_TYPE, ProductAdminDto.class, json);
    this.products = products;
    this.service = service;
    this.mediaReferences = mediaReferences;
    this.jdbc = jdbc;
    this.clock = clock;
    this.json = json;
  }

  /**
   * Only the restore reads this, inside its transaction, before anything else: the row is locked
   * there, so a save or a show or hide of the same product waits until the restore is done.
   */
  @Override
  protected Optional<ProductAdminDto> find(long entityId) {
    return products.findByIdForUpdate(entityId).map(ProductAdminDto::from);
  }

  /**
   * Restores the fields, then the switch only when the line changed it. A new row (a deleted
   * product) is inserted hidden, because the column default is false.
   */
  @Override
  public void restore(long entityId, String snapshotJson, String lineAfterJson) {
    restore(entityId, snapshotJson);
    Boolean switchBefore = switchChangedByLine(snapshotJson, lineAfterJson);
    if (switchBefore != null) {
      service.writeVisible(products.findById(entityId).orElseThrow(), switchBefore);
    }
  }

  @Override
  protected void restore(long entityId, ProductAdminDto snapshot) {
    ProductRequest request = checkedRequest(entityId, snapshot);
    mediaReferences.requireAllExist(request.mediaIds());
    Product product =
        products.findByIdForUpdate(entityId).orElseGet(() -> insertWithId(entityId, request));
    service.apply(product, request);
  }

  /**
   * The "before" value of the switch when the line changed it (both sides have it and they
   * differ), otherwise null. Lines from before migration V3 have no switch, so they never change it.
   */
  private Boolean switchChangedByLine(String beforeJson, String afterJson) {
    if (afterJson == null) {
      return null;
    }
    try {
      JsonNode before = json.readTree(beforeJson).path("visible");
      JsonNode after = json.readTree(afterJson).path("visible");
      if (before.isBoolean() && after.isBoolean() && before.asBoolean() != after.asBoolean()) {
        return before.asBoolean();
      }
      return null;
    } catch (JacksonException e) {
      throw badSnapshot();
    }
  }

  /** Validates the whole snapshot, before anything is written. */
  private ProductRequest checkedRequest(long entityId, ProductAdminDto snapshot) {
    if (snapshot.id() != entityId) {
      throw badSnapshot();
    }
    List<PackagingDto> packagings = snapshot.packagings() == null ? List.of() : snapshot.packagings();
    for (PackagingDto packaging : packagings) {
      if (packaging == null
          || packaging.weightGrams() == null
          || packaging.weightGrams() <= 0
          || (packaging.priceVnd() != null && packaging.priceVnd() < 0)) {
        throw badSnapshot();
      }
    }
    List<Long> mediaIds = snapshot.mediaIds() == null ? List.of() : snapshot.mediaIds();
    var seen = new HashSet<Long>();
    for (Long mediaId : mediaIds) {
      if (mediaId == null || !seen.add(mediaId)) {
        throw badSnapshot();
      }
    }
    var request =
        new ProductRequest(
            snapshot.sortOrder(),
            snapshot.showPrice(),
            snapshot.name(),
            snapshot.description(),
            snapshot.features(),
            snapshot.cookingTips(),
            packagings,
            mediaIds);
    try {
      service.validateTexts(request);
    } catch (ApiException e) {
      throw badSnapshot();
    }
    return request;
  }

  private Product insertWithId(long id, ProductRequest request) {
    Timestamp now = Timestamp.from(clock.instant());
    jdbc.update(
        "insert into product (id, sort_order, show_price, created_at, updated_at)"
            + " values (?, ?, ?, ?, ?)",
        id,
        request.sortOrder(),
        request.showPrice(),
        now,
        now);
    return products.findById(id).orElseThrow();
  }
}
